@dataclass
class TraceRecord:
    """Per-step audit record produced by :meth:`FaultInjector.apply`."""

    step: int
    availability: dict[str, bool]
    source_step: dict[str, Optional[int]]
    source_age_steps: dict[str, Optional[int]]
    faulted_observation_produced: bool
    mode: str
    active: bool

    def as_dict(self) -> dict[str, Any]:
        return {
            "step": self.step,
            "availability": dict(self.availability),
            "source_step": dict(self.source_step),
            "source_age_steps": dict(self.source_age_steps),
            "faulted_observation_produced": self.faulted_observation_produced,
            "mode": self.mode,
            "active": self.active,
        }


class FaultInjector:
    """Stateful availability fault injector.

    Call :meth:`apply` once per control step, in increasing step order, with
    the *healthy* observation for that step.  The injector keeps the healthy
    history it needs (freeze / stale) and enforces the causal rule from the
    module docstring on every delivery.
    """

    def __init__(self, schedule: FaultSchedule) -> None:
        self.schedule = schedule
        self._history: dict[str, dict[int, Any]] = {}
        self._last_step: Optional[int] = None
        self.faulted_observations_produced = 0
        self.trace: list[TraceRecord] = []

    # -- helpers ---------------------------------------------------------
    def _record(self, step: int, healthy_obs: Mapping[str, Any]) -> None:
        for cam, frame in healthy_obs.items():
            self._history.setdefault(cam, {})[step] = frame

    def _pre_onset_frame(self, cam: str) -> tuple[Optional[int], Any]:
        """Latest recorded frame with ``source_step < onset_step``."""
        hist = self._history.get(cam, {})
        # The last frame that was actually there: a pre-onset step whose frame
        # was None is not a frame to freeze on.
        candidates = [s for s in hist if s < self.schedule.onset_step and hist[s] is not None]
        if not candidates:
            return None, None
        s = max(candidates)
        return s, hist[s]

    def _camera_available_this_step(self, step: int) -> bool:
        """Availability for the faulted cameras at ``step`` under ``burst_dropout``."""
        sched = self.schedule
        return burst_available(sched.fault_seed, step - sched.onset_step, sched.burst_frames, sched.available_rate)

    # -- main entry point --------------------------------------------------
    def apply(self, step: int, healthy_obs: Mapping[str, Any]) -> tuple[dict[str, Any], dict[str, bool], TraceRecord]:
        """Apply the fault to ``healthy_obs`` at ``step``.

        Returns ``(obs, availability, trace_record)`` where ``obs`` is the
        observation to hand to the policy, ``availability`` maps every camera
        id to a boolean and ``trace_record`` is a :class:`TraceRecord`.
        """
        if self._last_step is not None and step <= self._last_step:
            raise ValueError(f"steps must be strictly increasing (got {step} after {self._last_step})")
        self._last_step = step
        self._record(step, healthy_obs)
        sched = self.schedule

        obs: dict[str, Any] = {}
        availability: dict[str, bool] = {}
        source_step: dict[str, Optional[int]] = {}
        source_age: dict[str, Optional[int]] = {}
        produced = False
        active = sched.active(step)

        for cam, frame in healthy_obs.items():
            if cam not in sched.faulted_cameras or not active:
                obs[cam] = frame
                availability[cam] = frame is not None
                source_step[cam] = step if frame is not None else None
                source_age[cam] = 0 if frame is not None else None
                continue

            mode = sched.mode
            delivered: Any = None
            avail = False
            src: Optional[int] = None

            if mode == "hard_missing":
                pass
            elif mode == "blackout":
                delivered, avail, src = zero_like(frame), True, step
            elif mode == "freeze":
                src, delivered = self._pre_onset_frame(cam)
                avail = src is not None
                if not avail:
                    delivered, src = None, None  # onset == 0 -> hard_missing
            elif mode == "stale_k":
                k = int(sched.stale_k)
                hist = self._history.get(cam, {})
                if step - k in hist and hist[step - k] is not None:
                    delivered, avail, src = hist[step - k], True, step - k
            elif mode == "burst_dropout":
                if self._camera_available_this_step(step):
                    delivered, avail, src = frame, True, step
            else:  # pragma: no cover - guarded by canonical_mode
                raise ValueError(mode)

            # Causal firewall: an unavailable camera never exposes post-onset frames.
            if not avail and src is not None and src >= sched.onset_step:
                raise CausalViolation(f"camera {cam} unavailable at step {step} but source_step={src}")
            # Freeze must never exceed onset even though it is 'available'.
            if mode == "freeze" and src is not None and src >= sched.onset_step:
                raise CausalViolation(f"freeze delivered post-onset frame {src} at step {step}")

            obs[cam] = delivered
            availability[cam] = avail
            source_step[cam] = src
            source_age[cam] = (step - src) if src is not None else None
            # The injector produces a faulted observation whenever the
            # delivered frame differs from the healthy one at this step. The
            # runner separately records whether a policy query consumed it.
            if not (avail and src == step and delivered is frame):
                produced = True

        if produced:
            self.faulted_observations_produced += 1
        record = TraceRecord(
            step=step,
            availability=availability,
            source_step=source_step,
            source_age_steps=source_age,
            faulted_observation_produced=produced,
            mode=sched.mode,
            active=active,
        )
        self.trace.append(record)
        return obs, availability, record

    def availability_trace_hash(self) -> str:
        """SHA256 over the per-step availability mapping (sorted camera ids)."""
        lines = []
        for rec in self.trace:
            bits = "".join("1" if rec.availability[c] else "0" for c in sorted(rec.availability))
            lines.append(f"{rec.step}:{bits}")
        return hashlib.sha256("\n".join(lines).encode("ascii")).hexdigest()


