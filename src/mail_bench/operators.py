# Poison test
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class Poison:
    """Sentinel frame that must never be delivered while a camera is unavailable."""

    camera: str
    step: int


@dataclass(frozen=True)
class HealthyFrame:
    """Sentinel healthy frame (pre-onset or non-faulted camera)."""

    camera: str
    step: int


def poison_test(
    injector: FaultInjector,
    camera_ids: Iterable[str],
    n_steps: int,
    frame_factory: Optional[Callable[[str, int], Any]] = None,
) -> dict[str, Any]:
    """Feed sentinel frames through ``injector`` and assert the causal rule.

    Post-onset frames of the faulted cameras are :class:`Poison` sentinels.
    After every step the helper asserts that

    * every unavailable camera receives ``None`` with no source step;
    * no :class:`Poison` is delivered to a camera whose availability is
      ``False``;
    * in ``freeze`` mode delivered frames always come from before onset.

    ``frame_factory(camera, step)`` may override how healthy (pre-onset)
    frames are built.  Returns a summary dictionary; raises
    :class:`CausalViolation` on the first breach.
    """
    cams = [str(c) for c in camera_ids]
    sched = injector.schedule
    delivered_poison = 0
    unavailable_steps = 0
    for step in range(int(n_steps)):
        healthy: dict[str, Any] = {}
        for cam in cams:
            if cam in sched.faulted_cameras and step >= sched.onset_step:
                healthy[cam] = Poison(cam, step)
            elif frame_factory is not None:
                healthy[cam] = frame_factory(cam, step)
            else:
                healthy[cam] = HealthyFrame(cam, step)
        obs, availability, rec = injector.apply(step, healthy)
        for cam in cams:
            frame = obs[cam]
            if not availability[cam]:
                unavailable_steps += 1
                if frame is not None or rec.source_step[cam] is not None:
                    raise CausalViolation(f"unavailable camera {cam} at step {step} delivered {frame!r}")
            if isinstance(frame, Poison):
                if not availability[cam]:
                    raise CausalViolation(f"poison {frame} delivered while unavailable")
                if sched.mode not in ("stale_k", "burst_dropout", "blackout") and cam in sched.faulted_cameras:
                    raise CausalViolation(f"poison {frame} delivered under mode {sched.mode}")
                delivered_poison += 1
            if sched.mode == "freeze" and cam in sched.faulted_cameras and sched.active(step):
                src = rec.source_step[cam]
                if src is not None and src >= sched.onset_step:
                    raise CausalViolation(f"freeze used post-onset frame {src}")
    return {
        "n_steps": int(n_steps),
        "unavailable_camera_steps": unavailable_steps,
        "poison_delivered_while_available": delivered_poison,
        "faulted_observations_produced": injector.faulted_observations_produced,
        "availability_trace_hash": injector.availability_trace_hash(),
    }
