"""Availability fault operators over per-step observation dictionaries.

An observation at control step ``t`` is a mapping ``{camera_id: frame}`` where
``frame`` is any object (a NumPy array, a nested list, a test sentinel, ...).
The injector rewrites that mapping according to a :class:`FaultSchedule` and
returns, for every step, the delivered observation, a per-camera availability
mapping and an auditable trace record.

Canonical availability modes (aliases in :data:`MODE_ALIASES`):

``hard_missing``
    Frame is ``None`` and ``available=False``.
``blackout``
    Frame is an all-zero frame of the same shape; ``available=True``.  The
    zero frame is fixed, so every arm sees the same pixels; only the
    availability semantics differ upstream.
``freeze``
    Repeats the last frame captured *strictly before* the onset step;
    ``available=True``.  If ``onset_step == 0`` no pre-onset frame exists and
    the operator degrades to ``hard_missing`` (never to ``blackout``, which
    would silently merge two distinct fault representations).
``stale_k``
    Delivers the frame captured ``k`` steps earlier if it exists, with
    ``available=True`` and ``source_age_steps = k``.  If the history is too
    short the step degrades to ``hard_missing``.  This is the documented
    *available-but-delayed* exception to the causal rule below: a stale camera
    may deliver post-onset frames because the stream is declared available.
``burst_dropout``
    A deterministic binary availability sequence generated by
    :func:`burst_schedule`.  During unavailable blocks the camera behaves as
    ``hard_missing``; during available blocks it is healthy.

Causal rule (enforced by :class:`FaultInjector` and checked by
:func:`poison_test`): for a camera that is *unavailable* at step ``t`` the
injector never delivers a frame whose ``source_step >= onset_step``.  Hidden
post-onset frames of an unavailable camera exist only for the scorer.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from typing import Any, Callable, Iterable, Mapping, Optional

CANONICAL_MODES = ("hard_missing", "blackout", "freeze", "stale_k", "burst_dropout")
MODE_ALIASES = {"missing": "hard_missing", "burst": "burst_dropout", "stale": "stale_k"}
RECOVERY_MODES = ("none", "single_recovery", "periodic_burst")


class CausalViolation(AssertionError):
    """Raised when a hidden post-onset frame would reach an unavailable camera."""


def canonical_mode(name: str) -> str:
    """Resolve a mode name or alias to its canonical name.

    Raises ``ValueError`` for unknown modes.
    """
    key = str(name).strip().lower()
    key = MODE_ALIASES.get(key, key)
    if key not in CANONICAL_MODES:
        raise ValueError(f"unknown availability fault mode: {name!r}")
    return key


# ---------------------------------------------------------------------------
# Deterministic burst schedule
# ---------------------------------------------------------------------------

#: Failure Form is specified in milliseconds so that one canonical setting means
#: the same thing on platforms with different control rates. Ten steps of stale
#: vision is half a second at 20 Hz and a third of one at 30 Hz; 500 ms is 500
#: ms everywhere.
CANONICAL_STALE_MS = 500
CANONICAL_BURST_BLOCK_MS = 500


def control_steps_for(milliseconds: float, control_hz: float) -> int:
    """Convert a canonical duration to this platform's control steps."""
    if control_hz <= 0:
        raise ValueError("control_hz must be > 0")
    if milliseconds < 0:
        raise ValueError("milliseconds must be >= 0")
    return max(1, int(milliseconds * control_hz / 1000.0 + 0.5))


def burst_draw(fault_seed: int, block_index: int, salt: str = "avail") -> float:
    """Deterministic uniform draw in ``[0, 1)`` for one burst block.

    ``SHA256("mcr_bench.burst|<fault_seed>|<block_index>|<salt>")`` is taken and
    the first eight bytes are scaled to ``[0, 1)``: one stable hash draw per
    key tuple, so the same seed and block always give the same draw.
    """
    # The payload prefix is a frozen identifier: changing it would change
    # every burst schedule.
    payload = f"mcr_bench.burst|{int(fault_seed)}|{int(block_index)}|{salt}".encode("utf-8")
    digest = hashlib.sha256(payload).digest()
    return int.from_bytes(digest[:8], "big") / 2**64


def burst_available(fault_seed: int, rel_step: int, burst_frames: int, available_rate: float) -> bool:
    """Availability of relative step ``rel_step`` under the burst rule.

    One draw is made per burst block of ``burst_frames`` steps
    (``block = rel_step // burst_frames``); the block is available iff
    ``draw < available_rate``.

    **The first block is always unavailable**, whatever the draw says. Without
    that, a burst cell whose first block happened to come up available would
    begin with no fault at all, and its onset would be somewhere later than the
    one the manifest records -- so two scenes with the same nominal onset would
    have been faulted at different points, and the difference would look like
    policy behaviour.
    """
    if burst_frames < 1:
        raise ValueError("burst_frames must be >= 1")
    if not 0.0 <= available_rate <= 1.0:
        raise ValueError("available_rate must be in [0, 1]")
    block = rel_step // burst_frames
    if block == 0:
        return False
    return burst_draw(fault_seed, block) < available_rate


def burst_schedule(fault_seed: int, n_steps: int, burst_frames: int, available_rate: float) -> list[bool]:
    """Binary availability sequence for ``n_steps`` relative steps.

    The sequence is a pure function of its arguments; the same fault seed
    always yields the same bits, so the schedule can be stored in a manifest
    and hashed (see :func:`burst_hash`).
    """
    return [burst_available(fault_seed, s, burst_frames, available_rate) for s in range(int(n_steps))]


def burst_hash(bits: Iterable[bool]) -> str:
    """SHA256 hex digest of a binary availability sequence."""
    return hashlib.sha256("".join("1" if b else "0" for b in bits).encode("ascii")).hexdigest()


# ---------------------------------------------------------------------------
# Zero frames
# ---------------------------------------------------------------------------

def zero_like(frame: Any) -> Any:
    """Return an all-zero frame with the same shape/type as ``frame``.

    Supports NumPy arrays (``zeros_like``), numbers, bytes and nested
    lists/tuples.  Other objects fall back to ``0`` so that the operator still
    delivers *something* that is unmistakably not the healthy frame.
    """
    try:
        import numpy as np
    except ImportError:  # pragma: no cover
        np = None
    if np is not None and isinstance(frame, np.ndarray):
        return np.zeros_like(frame)
    if isinstance(frame, bool):
        return False
    if isinstance(frame, (int, float)):
        return type(frame)(0)
    if isinstance(frame, (bytes, bytearray)):
        return type(frame)(len(frame))
    if isinstance(frame, (list, tuple)):
        return type(frame)(zero_like(v) for v in frame)
    return 0


