@dataclass(frozen=True)
class FaultSchedule:
    """Frozen description of one availability fault cell.

    Parameters
    ----------
    faulted_cameras:
        Camera ids affected by the fault.
    mode:
        Canonical mode or alias (resolved on construction).
    onset_step:
        First faulted control step (inclusive).
    end_step:
        First step after the fault (exclusive); ``None`` = until episode end.
    stale_k:
        Delay in control steps for ``stale_k``.
    burst_frames, available_rate:
        Burst-block length and per-block availability probability for
        ``burst_dropout``.
    recovery:
        ``none`` (permanent), ``single_recovery`` (healthy again from
        ``end_step``) or ``periodic_burst`` (only meaningful with
        ``burst_dropout``).
    """

    faulted_cameras: frozenset[str]
    mode: str = "hard_missing"
    onset_step: int = 0
    end_step: Optional[int] = None
    stale_k: Optional[int] = None
    burst_frames: int = 15
    available_rate: float = 0.5
    fault_seed: int = 0
    recovery: str = "none"

    def __post_init__(self) -> None:
        object.__setattr__(self, "faulted_cameras", frozenset(str(c) for c in self.faulted_cameras))
        object.__setattr__(self, "mode", canonical_mode(self.mode))
        if self.onset_step < 0:
            raise ValueError("onset_step must be >= 0")
        if self.end_step is not None and self.end_step <= self.onset_step:
            raise ValueError("end_step must be > onset_step (exclusive end) or None")
        if self.recovery not in RECOVERY_MODES:
            raise ValueError(f"unknown recovery mode {self.recovery!r}; expected one of {RECOVERY_MODES}")
        if self.recovery == "none" and self.end_step is not None:
            raise ValueError("recovery='none' means permanent failure; end_step must be None")
        if self.recovery == "single_recovery" and self.end_step is None:
            raise ValueError("recovery='single_recovery' requires a finite end_step")
        if self.recovery == "periodic_burst" and self.mode != "burst_dropout":
            raise ValueError("recovery='periodic_burst' requires mode='burst_dropout'")
        if self.mode == "stale_k" and (self.stale_k is None or self.stale_k < 1):
            raise ValueError("stale_k mode requires stale_k >= 1")
        if self.mode == "burst_dropout":
            if self.burst_frames < 1:
                raise ValueError("burst_frames must be >= 1")
            if not 0.0 <= self.available_rate <= 1.0:
                raise ValueError("available_rate must be in [0, 1]")

    def active(self, step: int) -> bool:
        """Whether the fault window covers ``step``."""
        if step < self.onset_step:
            return False
        return self.end_step is None or step < self.end_step


